// Generates migrations/0003_seed_builtin.sql: the built-in drills (conditions, presentations, systems review) as quizzes
// and the three built-in playlists, all owned by the placeholder user `ollie`. Run once and commit the result:
//   node scripts/seed-builtins.mjs
// The ids are random UUIDv7s, so the script refuses to overwrite an existing file (regenerating would change every id).
import { existsSync, readFileSync, writeFileSync } from "fs";
import { v7 } from "uuid";

const dir = new URL("../src/recall-drill/", import.meta.url);
const out = new URL("../migrations/0003_seed_builtin.sql", import.meta.url);
if (existsSync(out)) {
  console.error(
    `${out.pathname} exists; delete it first if you really want new ids.`,
  );
  process.exit(1);
}

const OWNER = "ollie";
const read = (f) => JSON.parse(readFileSync(new URL(f, dir), "utf8"));
const sql = (s) => "'" + s.replaceAll("'", "''") + "'";

// Titles and descriptions mirror src/recall-drill/lib/playlists.js (which can't be imported in Node: it pulls in SVG assets)
const PLAYLISTS = [
  {
    mode: "cond",
    file: "conditions.json",
    title: "Conditions",
    description:
      "Presentation, risk factors, examination, investigations and management for common conditions, by body system.",
  },
  {
    mode: "pres",
    file: "presentations.json",
    title: "Presentations",
    description:
      "Work up a presenting complaint: differentials, associated features and investigations.",
  },
  {
    mode: "sys",
    file: "systems-review.json",
    title: "Systems review",
    description:
      "Symptoms to ask about for each body system and clinical context.",
  },
];

// Increasing timestamps, one second apart, so ORDER BY id follows file order
let tick = Date.UTC(2026, 9, 1);
const nextId = () => v7({ msecs: (tick += 1000) });

const lines = [
  "-- Generated by scripts/seed-builtins.mjs: built-in quizzes and playlists, owned by the placeholder user `ollie`.",
  "-- history.quiz_id is NOT rewritten here: the client still keys drills by `mode|system|name` (a quiz's legacy key) until the UI switches over.",
  "",
  "-- The owner must exist (migration 0001 creates it from the old accounts; a fresh database has none).",
  `INSERT OR IGNORE INTO users (id, name, email, emailVerified, createdAt, updatedAt) VALUES (${sql(OWNER)}, ${sql(OWNER)}, ${sql(OWNER + "@legacy.invalid")}, 0, '2026-10-01T00:00:00.000Z', '2026-10-01T00:00:00.000Z');`,
  "",
];

const playlists = [];
let quizzes = 0;
for (const pl of PLAYLISTS) {
  const sections = [];
  for (const [system, drills] of Object.entries(read(pl.file))) {
    const ids = [];
    for (const [name, drill] of Object.entries(drills)) {
      const id = nextId();
      const { prompt, ...rest } = drill;
      const data = {
        mode: pl.mode,
        system,
        name,
        prompt,
        ...rest,
        deleted: false,
      };
      lines.push(
        `INSERT INTO quizzes (id, owner_id, data) VALUES (${sql(id)}, ${sql(OWNER)}, ${sql(JSON.stringify(data))});`,
      );
      ids.push(id);
      quizzes++;
    }
    sections.push({ title: system, quiz_ids: ids });
  }
  playlists.push({ id: nextId(), pl, sections });
}

lines.push("");
for (const { id, pl, sections } of playlists) {
  const data = { title: pl.title, description: pl.description, sections };
  lines.push(
    `INSERT INTO playlists (id, owner_id, data) VALUES (${sql(id)}, ${sql(OWNER)}, ${sql(JSON.stringify(data))});`,
  );
}

writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${quizzes} quizzes and ${playlists.length} playlists`);
